"""Generate the cheat-sheet site's data (docs/site/): one short clip per preset, played by the firmware itself on
this computer (the host build, tests/host.c), the preset list read from firmware/src/clavioline.c, and the screens.

    python3 tools/gen_site.py          (numpy, soundfile with MP3 support and Pillow needed; CC=gcc on Windows)

Run it again whenever the presets or the sound change: the page (docs/index.html) only reads what this writes."""
import json
import os
import re
import subprocess
import sys
import wave
from pathlib import Path

import numpy as np
import soundfile as sf
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
SITE = ROOT / "docs" / "site"
BUILD = ROOT / "build" / "site"
EXE = BUILD / ("clavioline.exe" if os.name == "nt" else "clavioline")
FS = 44100

CHIP = {"V3": "III", "V2": "II", "V1": "I", "AMP": "+", "SUB1P": "Ip", "SUB2P": "IIp", "SUB1F": "If", "SUB2F": "IIf"}
ORDER = ["III", "II", "I", "+", "Ip", "IIp", "If", "IIf", "1", "2", "3", "4", "5", "6", "7", "8", "9", "O", "A", "B",
         "V", "P"]
SOURCE = {"EE": "1952 table", "SOS": "Selmer card", "NEW": "new, not historical", "the Concert": "Concert sub-octaves"}
FAMILY = [("Reeds and winds", ("SAX", "OBOE", "BASSOON", "ENGLISH HORN", "REED", "BAGPIPE", "FLUTE", "PICCOLO", "FIFE")),
          ("Brass", ("TRUMPET", "CORNET", "TROMBONE", "HORN", "TUBA")),
          ("Strings", ("VIOLIN", "VIOLA", "VLN", "CELLO", "SAW")),
          ("Plucked", ("BANJO", "MANDOLIN", "GUITAR", "HARPSICHORD", "ZITHER")),
          ("Organs", ("ORGAN", "CELESTA"))]


def presets():
    src = (ROOT / "firmware/src/clavioline.c").read_text(encoding="utf-8")
    out = []
    for name, expr, cpl, tag in re.findall(r'^    \{"([A-Z0-9 ]+)", (.+?), (LOW|MED|HIGH)\},\s*/\* (EE|SOS|NEW|the Concert)', src, re.M):
        toks = re.findall(r'T\((\w+)\)|\b(V[123]|AMP)\b', expr)
        chips = [CHIP.get(t or v, t or v) for t, v in toks]
        chips.sort(key=ORDER.index)
        fam = next((f for f, keys in FAMILY if any(re.search(rf"\b{k}\b", name) for k in keys)), "Other")
        out.append({"name": name.title().replace("Vln", "Violin"), "key": name, "slug": name.lower().replace(" ", "-"),
                    "coupler": cpl, "chips": chips, "source": SOURCE[tag], "new": tag == "NEW", "family": fam})
    return out


def build():
    BUILD.mkdir(parents=True, exist_ok=True)
    cc = os.environ.get("CC", "cc")
    subprocess.run([cc, "-O2", "-w", "-DDINGHY_HOST", '-DAPP_VER="dev"', "-Ifirmware/hal", "-Ifirmware/src",
                    "-Ifirmware/gen", "-o", str(EXE), "firmware/src/clavioline.c"], cwd=ROOT, check=True)


def phrase():
    keys = []
    for line in (ROOT / "tests/scripts/demo.txt").read_text().splitlines():
        p = line.split()
        if len(p) == 3 and p[1] == "keys":
            if int(p[0]) > 6000:
                break
            keys.append((int(p[0]), p[2]))
    return keys


def run(script, out):
    (BUILD / (out + ".txt")).write_text("\n".join(script) + "\n")
    subprocess.run([str(EXE), str(BUILD / out), str(BUILD / (out + ".txt"))], cwd=ROOT, check=True,
                   stdout=subprocess.DEVNULL)


def clip(index, home, keys, slug):
    script = ([f"1500 enc 0 {index - home}"] if index != home else []) + [f"{t + 1500} keys {k}" for t, k in keys]
    run(script + ["8200 end"], slug)
    with wave.open(str(BUILD / (slug + ".wav"))) as w:
        x = np.frombuffer(w.readframes(w.getnframes()), dtype=np.int16).reshape(-1, 2)[:, 0].astype(float)
    x = x[int(1.95 * FS):int(1.95 * FS) + 2 * int(2.825 * FS)]
    x = (x[0::2] + x[1::2]) / 2                 # 22.05 kHz is plenty for a preview
    x *= 0.7 / (np.abs(x).max() + 1e-9)         # (levels evened out for browsing; they differ on the instrument)
    fade = np.minimum(1, np.arange(len(x))[::-1] / (0.05 * FS / 2))
    sf.write(str(SITE / "clips" / (slug + ".mp3")), x * fade, FS // 2, format="MP3")


def main():
    (SITE / "clips").mkdir(parents=True, exist_ok=True)
    build()
    ps = presets()
    home = next(i for i, p in enumerate(ps) if p["key"] == "CLAVIOLINE TONE")
    keys = phrase()
    for i, p in enumerate(ps):
        clip(i, home, keys, p["slug"])
        print(f"{i + 1:2d}/{len(ps)} {p['name']}", flush=True)
    # the screens: PLAY with a note, STOPS with the guide
    run(["1800 keys 0x80", "2100 shot", "2300 keys 0", "2400 btn 7", "2700 shot", "2800 end"], "screens")
    for t, name in (("2100", "play"), ("2700", "stops")):
        Image.open(BUILD / f"screens-{t}.ppm").resize((480, 480), Image.NEAREST).save(SITE / f"{name}.png", optimize=True)
    (SITE / "presets.js").write_text("/* generated by tools/gen_site.py from firmware/src/clavioline.c */\n"
                                     "const PRESETS = " + json.dumps(ps, indent=1) + ";\n", encoding="utf-8")
    print(f"{len(ps)} presets -> {SITE}")


if __name__ == "__main__":
    sys.exit(main())
