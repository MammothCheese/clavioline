"""Render a TrueType font into the firmware's proportional bitmap format (felucca_font_t: 4-bit alpha, a pen pad on
each side). Pillow needed.

    python3 tools/gen_font.py NAME FONT.ttf OUT.h --height 32 --cap 19 --base 27 [--first 32 --last 95 --track 2]

The title font: python3 tools/gen_font.py FONT_T assets/fonts/Orbitron.ttf firmware/gen/title_font.h
(cap height chosen so that CLAVIOLINE fits beside the satellite)."""
import argparse
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont


def font_for_cap(path, cap):
    """the point size whose capital H is cap pixels tall"""
    for s in range(4, 200):
        f = ImageFont.truetype(str(path), s)
        if -f.getbbox("H", anchor="ls")[1] >= cap:
            return f
    raise ValueError("cap height out of range")


def build(name, path, h, cap, base, first, last, pad, track):
    f = font_for_cap(path, cap)
    adv, bw, off, data = [], [], [], []
    for c in range(first, last + 1):
        a = int(round(f.getlength(chr(c)))) + track
        w = pad + a + pad
        im = Image.new("L", (w, h), 0)
        ImageDraw.Draw(im).text((pad, base), chr(c), font=f, fill=255, anchor="ls")
        px = im.load()
        off.append(len(data))
        for y in range(h):
            row = [0] * ((w + 1) // 2)
            for x in range(w):
                v = px[x, y] >> 4
                row[x // 2] |= (v << 4) if x % 2 == 0 else v
            data.extend(row)
        adv.append(a)
        bw.append(w)
    n = last - first + 1
    out = [f"static const uint8_t {name}_DATA[{len(data)}] = {{"]
    out += ["    " + ", ".join(f"0x{v:02x}" for v in data[i:i + 24]) + "," for i in range(0, len(data), 24)]
    out.append("};")
    out.append(f"static const uint16_t {name}_OFF[{n}] = {{{', '.join(map(str, off))}}};")
    out.append(f"static const uint8_t {name}_ADV[{n}] = {{{', '.join(map(str, adv))}}};")
    out.append(f"static const uint8_t {name}_BW[{n}] = {{{', '.join(map(str, bw))}}};")
    out.append(f"static const felucca_font_t {name} = {{ {h}, {pad}, {first}, {last}, {name}_ADV, {name}_BW, "
               f"{name}_OFF, {name}_DATA }};")
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("name")
    ap.add_argument("ttf", type=Path)
    ap.add_argument("out", type=Path)
    ap.add_argument("--height", type=int, default=32)
    ap.add_argument("--cap", type=int, default=19)
    ap.add_argument("--base", type=int, default=27)
    ap.add_argument("--first", type=int, default=32)
    ap.add_argument("--last", type=int, default=95)    # (no lower case: it folds to upper case)
    ap.add_argument("--pad", type=int, default=4)
    ap.add_argument("--track", type=int, default=2)
    a = ap.parse_args()
    body = build(a.name, a.ttf, a.height, a.cap, a.base, a.first, a.last, a.pad, a.track)
    a.out.write_text(f"/* generated by tools/gen_font.py from {a.ttf.name} (cap {a.cap} px, {a.height} px cell, "
                     f"characters {a.first}..{a.last}); see LICENSING.md */\n#pragma once\n\n{body}\n",
                     encoding="utf-8", newline="\n")
    print(a.out)


if __name__ == "__main__":
    main()
