"""Generate firmware/src/clav_tables.h: the integer tables clavioline.c runs on (the chip has no FPU).

    python3 tools/gen_clav_tables.py          (needs numpy; rerun after changing a constant here)

Every constant is tagged:
  PRINTED   a value legible in Electronic Engineering, Oct. 1952, Fig. 2 (the source of truth)
  DERIVED   follows from printed values
  ESTIMATE  not documented anywhere we have; chosen by ear / typical valve data. Change freely.
"""
import math
from pathlib import Path
import sys
sys.path.insert(0, str(Path(__file__).resolve().parent))

import numpy as np

FS = 44100.0
OUT = Path(__file__).resolve().parent.parent / "firmware" / "src" / "clav_tables.h"

# ---- V2 (6BA6) cathode network, Fig. 2 -------------------------------------------------------------
# Nodes: S (C1), Q (C2), K (C3, the cathode). K-R7-P-R4-Q-R3-S. Tablet P (S2) joins S and P.
# A key's second contact grounds S through R1. R8 feeds K from HT.
R1, R3, R4, R7, R8 = 1e3, 50e3, 2.5e3, 5e3, 500e3       # PRINTED
R_CATH = 12e3      # ESTIMATE: on release the valve's own cathode current charges C3 and cuts it off in a few ms
                   # (R8 alone would take 0.2 s); fitted so repeated P notes re-spike as in a recording
C1, C2, C3 = 0.1e-6, 0.1e-6, 0.25e-6                    # PRINTED
# Normalised: 1 = the quiescent (cut-off) cathode voltage, 0 = fully conducting. The printed bias resistors
# (R8, preset R2, unknown HT) do not give consistent absolute levels (docs/HISTORY.md), so only the
# time constants are taken from the circuit: key down discharges the ladder to 0 through R1, key up
# recharges it to 1 through R8. V2's own cathode current is ignored (first-order model).


def ladder(p_on: bool, key: bool):
    """x = [Vs, Vq, Vk]; dx/dt = A x + b"""
    G = np.zeros((3, 3))
    src = np.zeros(3)

    def link(i, j, r):
        g = 1.0 / r
        G[i, i] += g; G[j, j] += g; G[i, j] -= g; G[j, i] -= g

    S, Q, K = 0, 1, 2
    if p_on:                       # S2 closed: P == S, so R7 joins K-S and R3 || R4 joins Q-S
        link(K, S, R7)
        link(Q, S, R3 * R4 / (R3 + R4))
    else:                          # P floats between R7 and R4: K-Q through R7 + R4
        link(K, Q, R7 + R4)
        link(Q, S, R3)
    if key:
        G[S, S] += 1.0 / R1        # to ground (target 0)
    else:
        G[K, K] += 1.0 / R8 + 1.0 / R_CATH     # to "1": through R8, and the cathode current
        src[K] += 1.0 / R8 + 1.0 / R_CATH
    Cm = np.diag([C1, C2, C3])
    A = -np.linalg.solve(Cm, G)
    b = np.linalg.solve(Cm, src)
    return A, b


def expm(M):
    w, V = np.linalg.eig(M)
    return (V @ np.diag(np.exp(w)) @ np.linalg.inv(V)).real


def discretise(A, b):
    T = 1.0 / FS
    Phi = expm(A * T)
    Gam = np.linalg.solve(A, (Phi - np.eye(3)) @ b) if np.any(b) else np.zeros(3)
    return Phi, Gam


def q30(x):
    return int(round(x * (1 << 30)))


lines = ["/* Generated by tools/gen_clav_tables.py: do not edit; change the script and rerun. */",
         "/* SPDX-License-Identifier: GPL-3.0-only */", "#pragma once", "#include <stdint.h>", ""]

lines.append("/* V2 cathode network, exact per-sample discretisation (Q30). [case] = key << 1 | P.")
lines.append(" * x' = PHI x + GAM, x = {Vs, Vq, Vk}; 1 = cut off, 0 = conducting (normalised, see the script).")
phis, gams, report = [], [], []
for key in (0, 1):
    for p in (0, 1):
        A, b = ladder(bool(p), bool(key))
        Phi, Gam = discretise(A, b)
        phis.append(Phi); gams.append(Gam)
        taus = sorted(-1.0 / np.linalg.eigvals(A).real, reverse=True)
        report.append(f" *   key {'down' if key else 'up  '} P {'on ' if p else 'off'}: time constants "
                      + ", ".join(f"{t * 1e3:.2f}" for t in taus) + " ms")
lines.append(" * DERIVED time constants (eigenvalues of the printed network):")
lines += report
lines.append(" */")
lines.append("static const int32_t GATE_PHI[4][3][3] = {")
for Phi in phis:
    lines.append("    {" + ", ".join("{" + ", ".join(str(q30(v)) for v in row) + "}" for row in Phi) + "},")
lines.append("};")
lines.append("static const int32_t GATE_GAM[4][3] = {")
for Gam in gams:
    lines.append("    {" + ", ".join(str(q30(v)) for v in Gam) + "},")
lines.append("};")
# the same over 8 samples (the ISR steps the gate every 8 samples and interpolates the gain between)
lines.append("static const int32_t GATE_PHI8[4][3][3] = {")
g8 = []
for Phi, Gam in zip(phis, gams):
    P8 = np.linalg.matrix_power(Phi, 8)
    G8 = sum(np.linalg.matrix_power(Phi, k) for k in range(8)) @ Gam
    g8.append(G8)
    lines.append("    {" + ", ".join("{" + ", ".join(str(q30(v)) for v in row) + "}" for row in P8) + "},")
lines.append("};")
lines.append("static const int32_t GATE_GAM8[4][3] = {")
for G8 in g8:
    lines.append("    {" + ", ".join(str(q30(v)) for v in G8) + "},")
lines.append("};")
lines.append("")

# ---- V2 gain versus normalised cathode voltage --------------------------------------------------------
# A remote-cut-off pentode's gain falls roughly exponentially with bias. VX sets how much of the cathode
# swing is audible. ESTIMATE: 0.12 gives ~72 dB from conducting to cut-off.
VX = 0.12                                                # ESTIMATE
floor = math.exp(-1.0 / VX)
lines.append(f"/* V2 gain (Q15) over v = 0..1 in 256 steps (+1 guard): (e^(-v/{VX}) - e^(-1/{VX})) / (1 - e^(-1/{VX})).")
lines.append(" * Remote-cut-off approximation; VX is an ESTIMATE. */")
g = [max(0.0, (math.exp(-(i / 256) / VX) - floor) / (1 - floor)) for i in range(257)]
g.append(0.0)
lines.append("static const uint16_t GATE_GAIN[258] = {")
for i in range(0, 258, 16):
    lines.append("    " + ", ".join(str(int(round(v * 32767))) for v in g[i:i + 16]) + ",")
lines.append("};")
lines.append("")

# ---- the oscillator's wavetables (tools/clav_wave.py: the multivibrator shape, ESTIMATE) --------------------
# One table per octave, band-limited for the 22.05 kHz rate the instrument runs at: table k serves fundamentals
# 27.5 * 2^k .. 27.5 * 2^(k+1) Hz with harmonics up to 10.5 kHz. The square tables are the Concert's divider outputs.
import clav_wave as wave
WT_N, WT_OCT = 1024, 8
lines.append(f"#define WT_N {WT_N}u")
lines.append(f"#define WT_OCT {WT_OCT}u")
lines.append(f"#define WT_INC0 {int(round(27.5 / 22050.0 * 2 ** 32))}u   /* the phase step of 27.5 Hz at 22.05 kHz */")
for name, src in (("WT_PULSE", wave.cycle(1 << 15)), ("WT_SQUARE", wave.square(1 << 15))):
    lines.append(f"static const int16_t {name}[WT_OCT][WT_N] = {{")
    for k in range(WT_OCT):
        nmax = int(10500.0 / (27.5 * 2 ** (k + 1)))
        t = wave.bandlimited(src, nmax, WT_N)
        t = t / np.abs(t).max()
        lines.append("    {" + ",".join(str(int(round(v * 32767))) for v in t) + "},")
    lines.append("};")
lines.append("")

# ---- decoding the fitted formant filters on the chip --------------------------------------------------------
lines.append("/* 2^(i/256) for i = 0..256, Q30: the chip decodes the formant table's log2 values with it */")
lines.append("static const int32_t EXP2_Q30[257] = {")
e2 = [int(round(2 ** (i / 256) * (1 << 30))) for i in range(257)]
e2[-1] = (1 << 31) - 1
for i in range(0, 257, 8):
    lines.append("    " + ", ".join(str(v) for v in e2[i:i + 8]) + ",")
lines.append("};")
lines.append("")

# ---- the knee lever ------------------------------------------------------------------------------------------
# R32 shunts the network's input. The formant filters are fitted with the lever open; here its effect is a level:
# the circuit model's average change (150 Hz..4 kHz, no tablets) for each lever step. Step 0: silent.
import clav_net_ref as net
LEVER_MAX = net.LEVER_MAX
fl = np.geomspace(150, 4000, 60)
h64 = np.abs(net.ac(0, LEVER_MAX, fl))
lg = [0]
for i in range(1, LEVER_MAX + 1):
    d = np.mean(20 * np.log10(np.abs(net.ac(0, i, fl)) / h64))
    lg.append(int(round(32767 * 10 ** (d / 20))))
lines.append(f"#define LEVER_MAX {LEVER_MAX}u")
lines.append("/* Knee lever gain (Q15) per step: the circuit model's level change with R32 (log taper, ESTIMATE). */")
lines.append(f"static const uint16_t LEVER_GAIN[{LEVER_MAX + 1}] = {{")
for i in range(0, len(lg), 13):
    lines.append("    " + ", ".join(str(v) for v in lg[i:i + 13]) + ",")
lines.append("};")
lines.append("")

# ---- the loudspeaker and cabinet (ESTIMATE: no data survives) -----------------------------------------------
# A 10-inch moving coil in the amplifier cabinet: a bass resonance, a presence peak, the cone's roll-off.
# RBJ biquads at 44.1 kHz, Q28: {b0, b1, b2, a1, a2}.
FS2 = 44100.0


def rbj(kind, f0, q, gain_db=0.0):
    w = 2 * np.pi * f0 / FS2
    c, s_ = np.cos(w), np.sin(w)
    al = s_ / (2 * q)
    A = 10 ** (gain_db / 40)
    if kind == "hp":
        b = [(1 + c) / 2, -(1 + c), (1 + c) / 2]; a = [1 + al, -2 * c, 1 - al]
    elif kind == "lp":
        b = [(1 - c) / 2, 1 - c, (1 - c) / 2]; a = [1 + al, -2 * c, 1 - al]
    else:
        b = [1 + al * A, -2 * c, 1 - al * A]; a = [1 + al / A, -2 * c, 1 - al / A]
    return [v / a[0] for v in b] + [a[1] / a[0], a[2] / a[0]]


SPK = [("hp", 100.0, 1.1, 0.0), ("peak", 2200.0, 1.0, 4.0), ("lp", 5500.0, 0.707, 0.0)]   # ESTIMATE
lines.append("/* Speaker and cabinet (ESTIMATE): high-pass 100 Hz Q 1.1 (the cabinet's bass resonance), +4 dB peak at")
lines.append(" * 2.2 kHz Q 1 (the cone's presence), low-pass 5.5 kHz Q 0.707 (its roll-off). 44.1 kHz, Q28. */")
lines.append("static const int32_t SPEAKER[3][5] = {")
for kind, f0, q, gdb in SPK:
    lines.append("    {" + ", ".join(str(int(round(v * (1 << 28)))) for v in rbj(kind, f0, q, gdb)) + "},")
lines.append("};")
lines.append("")

# ---- fine tuning (VR6 equivalent) ----------------------------------------------------------------------
lines.append("/* Fine tune: 2^(c/1200) in Q16 for c = -50..+50 cents. */")
tune = [int(round(65536 * 2 ** (c / 1200))) for c in range(-50, 51)]
lines.append("static const uint32_t TUNE_Q16[101] = {")
for i in range(0, 101, 10):
    lines.append("    " + ", ".join(str(v) for v in tune[i:i + 10]) + ",")
lines.append("};")
lines.append("")

OUT.write_text("\n".join(lines) + "\n")
print("wrote", OUT)
print("\n".join(r[3:] for r in report))
