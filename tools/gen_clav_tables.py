"""Generate firmware/src/clav_tables.h: the integer tables clavioline.c runs on (the chip has no FPU).

    python3 tools/gen_clav_tables.py          (needs numpy; rerun after changing a constant here)

Every constant is tagged:
  PRINTED   a value legible in Electronic Engineering, Oct. 1952, Fig. 2 (the source of truth)
  DERIVED   follows from printed values
  ESTIMATE  not documented anywhere we have; chosen by ear / typical valve data. Change freely.
"""
import math
from pathlib import Path

import numpy as np

FS = 44100.0
OUT = Path(__file__).resolve().parent.parent / "firmware" / "src" / "clav_tables.h"

# ---- V2 (6BA6) cathode network, Fig. 2 -------------------------------------------------------------
# Nodes: S (C1), Q (C2), K (C3, the cathode). K-R7-P-R4-Q-R3-S. Tablet P (S2) joins S and P.
# A key's second contact grounds S through R1. R8 feeds K from HT.
R1, R3, R4, R7, R8 = 1e3, 50e3, 2.5e3, 5e3, 500e3       # PRINTED
C1, C2, C3 = 0.1e-6, 0.1e-6, 0.25e-6                    # PRINTED
# Normalised: 1 = the quiescent (cut-off) cathode voltage, 0 = fully conducting. The printed bias resistors
# (R8, preset R2, unknown HT) do not give consistent absolute levels (Stage 1 analysis, U6), so only the
# time constants are taken from the circuit: key down discharges the ladder to 0 through R1, key up
# recharges it to 1 through R8. V2's own cathode current is ignored (first-order model).


def ladder(p_on: bool, key: bool):
    """x = [Vs, Vq, Vk]; dx/dt = A x + b"""
    G = np.zeros((3, 3))
    src = np.zeros(3)

    def link(i, j, r):
        g = 1.0 / r
        G[i, i] += g; G[j, j] += g; G[i, j] -= g; G[j, i] -= g

    S, Q, K = 0, 1, 2
    if p_on:                       # S2 closed: P == S, so R7 joins K-S and R3 || R4 joins Q-S
        link(K, S, R7)
        link(Q, S, R3 * R4 / (R3 + R4))
    else:                          # P floats between R7 and R4: K-Q through R7 + R4
        link(K, Q, R7 + R4)
        link(Q, S, R3)
    if key:
        G[S, S] += 1.0 / R1        # to ground (target 0)
    else:
        G[K, K] += 1.0 / R8        # to "1" through R8
        src[K] += 1.0 / R8
    Cm = np.diag([C1, C2, C3])
    A = -np.linalg.solve(Cm, G)
    b = np.linalg.solve(Cm, src)
    return A, b


def expm(M):
    w, V = np.linalg.eig(M)
    return (V @ np.diag(np.exp(w)) @ np.linalg.inv(V)).real


def discretise(A, b):
    T = 1.0 / FS
    Phi = expm(A * T)
    Gam = np.linalg.solve(A, (Phi - np.eye(3)) @ b) if np.any(b) else np.zeros(3)
    return Phi, Gam


def q30(x):
    return int(round(x * (1 << 30)))


lines = ["/* Generated by tools/gen_clav_tables.py: do not edit; change the script and rerun. */",
         "/* SPDX-License-Identifier: GPL-3.0-only */", "#pragma once", "#include <stdint.h>", ""]

lines.append("/* V2 cathode network, exact per-sample discretisation (Q30). [case] = key << 1 | P.")
lines.append(" * x' = PHI x + GAM, x = {Vs, Vq, Vk}; 1 = cut off, 0 = conducting (normalised, see the script).")
phis, gams, report = [], [], []
for key in (0, 1):
    for p in (0, 1):
        A, b = ladder(bool(p), bool(key))
        Phi, Gam = discretise(A, b)
        phis.append(Phi); gams.append(Gam)
        taus = sorted(-1.0 / np.linalg.eigvals(A).real, reverse=True)
        report.append(f" *   key {'down' if key else 'up  '} P {'on ' if p else 'off'}: time constants "
                      + ", ".join(f"{t * 1e3:.2f}" for t in taus) + " ms")
lines.append(" * DERIVED time constants (eigenvalues of the printed network):")
lines += report
lines.append(" */")
lines.append("static const int32_t GATE_PHI[4][3][3] = {")
for Phi in phis:
    lines.append("    {" + ", ".join("{" + ", ".join(str(q30(v)) for v in row) + "}" for row in Phi) + "},")
lines.append("};")
lines.append("static const int32_t GATE_GAM[4][3] = {")
for Gam in gams:
    lines.append("    {" + ", ".join(str(q30(v)) for v in Gam) + "},")
lines.append("};")
lines.append("")

# ---- V2 gain versus normalised cathode voltage --------------------------------------------------------
# A remote-cut-off pentode's gain falls roughly exponentially with bias. VX sets how much of the cathode
# swing is audible. ESTIMATE: 0.12 gives ~72 dB from conducting to cut-off.
VX = 0.12                                                # ESTIMATE
floor = math.exp(-1.0 / VX)
lines.append(f"/* V2 gain (Q15) over v = 0..1 in 256 steps (+1 guard): (e^(-v/{VX}) - e^(-1/{VX})) / (1 - e^(-1/{VX})).")
lines.append(" * Remote-cut-off approximation; VX is an ESTIMATE. */")
g = [max(0.0, (math.exp(-(i / 256) / VX) - floor) / (1 - floor)) for i in range(257)]
g.append(0.0)
lines.append("static const uint16_t GATE_GAIN[258] = {")
for i in range(0, 258, 16):
    lines.append("    " + ", ".join(str(int(round(v * 32767))) for v in g[i:i + 16]) + ",")
lines.append("};")
lines.append("")

# ---- the knee lever (R32): taper ----------------------------------------------------------------------
# "special construction and grading" (PRINTED, no values). At rest: "almost no sound" (Sound On Sound).
# ESTIMATE: 0 = silent, then dB-linear from -45 dB to 0 dB over LEVER_MAX steps.
LEVER_MAX = 64
LEVER_RANGE_DB = 45.0                                    # ESTIMATE
lv = [0] + [int(round(32767 * 10 ** ((-LEVER_RANGE_DB * (1 - i / LEVER_MAX)) / 20))) for i in range(1, LEVER_MAX + 1)]
lines.append(f"#define LEVER_MAX {LEVER_MAX}u")
lines.append(f"/* Knee lever taper (Q15): 0 = silent, then dB-linear -{LEVER_RANGE_DB:g}..0 dB. ESTIMATE (R32's grading is not printed). */")
lines.append(f"static const uint16_t LEVER_GAIN[{LEVER_MAX + 1}] = {{")
for i in range(0, len(lv), 13):
    lines.append("    " + ", ".join(str(v) for v in lv[i:i + 13]) + ",")
lines.append("};")
lines.append("")

# ---- fine tuning (VR6 equivalent) ----------------------------------------------------------------------
lines.append("/* Fine tune: 2^(c/1200) in Q16 for c = -50..+50 cents. */")
tune = [int(round(65536 * 2 ** (c / 1200))) for c in range(-50, 51)]
lines.append("static const uint32_t TUNE_Q16[101] = {")
for i in range(0, 101, 10):
    lines.append("    " + ", ".join(str(v) for v in tune[i:i + 10]) + ",")
lines.append("};")
lines.append("")

OUT.write_text("\n".join(lines) + "\n")
print("wrote", OUT)
print("\n".join(r[3:] for r in report))
