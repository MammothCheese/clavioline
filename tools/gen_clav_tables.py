"""Generate firmware/src/clav_tables.h: the integer tables clavioline.c runs on (the chip has no FPU).

    python3 tools/gen_clav_tables.py          (needs numpy; rerun after changing a constant here)

Every constant is tagged:
  PRINTED   a value legible in Electronic Engineering, Oct. 1952, Fig. 2 (the source of truth)
  DERIVED   follows from printed values
  ESTIMATE  not documented anywhere we have; chosen by ear / typical valve data. Change freely.
"""
import math
from pathlib import Path
import sys
sys.path.insert(0, str(Path(__file__).resolve().parent))

import numpy as np

FS = 44100.0
OUT = Path(__file__).resolve().parent.parent / "firmware" / "src" / "clav_tables.h"

# ---- V2 (6BA6) cathode network, Fig. 2 -------------------------------------------------------------
# Nodes: S (C1), Q (C2), K (C3, the cathode). K-R7-P-R4-Q-R3-S. Tablet P (S2) joins S and P.
# A key's second contact grounds S through R1. R8 feeds K from HT.
R1, R3, R4, R7, R8 = 1e3, 50e3, 2.5e3, 5e3, 500e3       # PRINTED
C1, C2, C3 = 0.1e-6, 0.1e-6, 0.25e-6                    # PRINTED
# Normalised: 1 = the quiescent (cut-off) cathode voltage, 0 = fully conducting. The printed bias resistors
# (R8, preset R2, unknown HT) do not give consistent absolute levels (docs/HISTORY.md), so only the
# time constants are taken from the circuit: key down discharges the ladder to 0 through R1, key up
# recharges it to 1 through R8. V2's own cathode current is ignored (first-order model).


def ladder(p_on: bool, key: bool):
    """x = [Vs, Vq, Vk]; dx/dt = A x + b"""
    G = np.zeros((3, 3))
    src = np.zeros(3)

    def link(i, j, r):
        g = 1.0 / r
        G[i, i] += g; G[j, j] += g; G[i, j] -= g; G[j, i] -= g

    S, Q, K = 0, 1, 2
    if p_on:                       # S2 closed: P == S, so R7 joins K-S and R3 || R4 joins Q-S
        link(K, S, R7)
        link(Q, S, R3 * R4 / (R3 + R4))
    else:                          # P floats between R7 and R4: K-Q through R7 + R4
        link(K, Q, R7 + R4)
        link(Q, S, R3)
    if key:
        G[S, S] += 1.0 / R1        # to ground (target 0)
    else:
        G[K, K] += 1.0 / R8        # to "1" through R8
        src[K] += 1.0 / R8
    Cm = np.diag([C1, C2, C3])
    A = -np.linalg.solve(Cm, G)
    b = np.linalg.solve(Cm, src)
    return A, b


def expm(M):
    w, V = np.linalg.eig(M)
    return (V @ np.diag(np.exp(w)) @ np.linalg.inv(V)).real


def discretise(A, b):
    T = 1.0 / FS
    Phi = expm(A * T)
    Gam = np.linalg.solve(A, (Phi - np.eye(3)) @ b) if np.any(b) else np.zeros(3)
    return Phi, Gam


def q30(x):
    return int(round(x * (1 << 30)))


lines = ["/* Generated by tools/gen_clav_tables.py: do not edit; change the script and rerun. */",
         "/* SPDX-License-Identifier: GPL-3.0-only */", "#pragma once", "#include <stdint.h>", ""]

lines.append("/* V2 cathode network, exact per-sample discretisation (Q30). [case] = key << 1 | P.")
lines.append(" * x' = PHI x + GAM, x = {Vs, Vq, Vk}; 1 = cut off, 0 = conducting (normalised, see the script).")
phis, gams, report = [], [], []
for key in (0, 1):
    for p in (0, 1):
        A, b = ladder(bool(p), bool(key))
        Phi, Gam = discretise(A, b)
        phis.append(Phi); gams.append(Gam)
        taus = sorted(-1.0 / np.linalg.eigvals(A).real, reverse=True)
        report.append(f" *   key {'down' if key else 'up  '} P {'on ' if p else 'off'}: time constants "
                      + ", ".join(f"{t * 1e3:.2f}" for t in taus) + " ms")
lines.append(" * DERIVED time constants (eigenvalues of the printed network):")
lines += report
lines.append(" */")
lines.append("static const int32_t GATE_PHI[4][3][3] = {")
for Phi in phis:
    lines.append("    {" + ", ".join("{" + ", ".join(str(q30(v)) for v in row) + "}" for row in Phi) + "},")
lines.append("};")
lines.append("static const int32_t GATE_GAM[4][3] = {")
for Gam in gams:
    lines.append("    {" + ", ".join(str(q30(v)) for v in Gam) + "},")
lines.append("};")
lines.append("")

# ---- V2 gain versus normalised cathode voltage --------------------------------------------------------
# A remote-cut-off pentode's gain falls roughly exponentially with bias. VX sets how much of the cathode
# swing is audible. ESTIMATE: 0.12 gives ~72 dB from conducting to cut-off.
VX = 0.12                                                # ESTIMATE
floor = math.exp(-1.0 / VX)
lines.append(f"/* V2 gain (Q15) over v = 0..1 in 256 steps (+1 guard): (e^(-v/{VX}) - e^(-1/{VX})) / (1 - e^(-1/{VX})).")
lines.append(" * Remote-cut-off approximation; VX is an ESTIMATE. */")
g = [max(0.0, (math.exp(-(i / 256) / VX) - floor) / (1 - floor)) for i in range(257)]
g.append(0.0)
lines.append("static const uint16_t GATE_GAIN[258] = {")
for i in range(0, 258, 16):
    lines.append("    " + ", ".join(str(int(round(v * 32767))) for v in g[i:i + 16]) + ",")
lines.append("};")
lines.append("")

# ---- the tone-forming network (Fig. 4): companion-model constants -----------------------------------------
# The netlist and every value are in tools/clav_net_ref.py (PRINTED / CONCERT / ESTIMATE tags there).
# Units on the chip: voltage 2^-16 V, current 2^-16 uA, conductance uS in Q12, impedance MOhm in Q28.
import clav_net_ref as net
Pn = net.P
def g_r(r): return 1e6 / r                       # uS
def g_c(c): return 2.0 * c * FS * 1e6           # uS (trapezoidal companion conductance)
def q12(x):
    v = int(round(x * 4096)); assert 0 <= v < 2**31, x; return v
G = {
    "R5": g_r(Pn["R5"]), "C5": g_c(Pn["C5"]), "C30": g_c(Pn["C30"]), "C24": g_c(Pn["C24"]), "C25": g_c(Pn["C25"]),
    "C26": g_c(Pn["C26"]), "C17": g_c(Pn["C17"]), "R29": g_r(Pn["R29"]), "R30": g_r(Pn["R30"]), "C28": g_c(Pn["C28"]),
    "R31": g_r(Pn["R31"]), "C29": g_c(Pn["C29"]), "RIN": g_r(Pn["RIN"]), "COUT": g_c(Pn["COUT"]), "RP_L5": g_r(Pn["RP_L5"]),
    "RPA": g_r(Pn["RPA"]), "RPB": g_r(Pn["RPB"]), "RPC": g_r(Pn["RPC"]), "SHORT": g_r(Pn["R_SHORT"]),
    "C18": g_c(Pn["C18"]), "C19": g_c(Pn["C19"]), "R28": g_r(Pn["R28"]), "C20": g_c(Pn["C20"]), "C21": g_c(Pn["C21"]),
    "R26": g_r(Pn["R26"]), "R27": g_r(Pn["R27"]), "C22": g_c(Pn["C22"]), "C23": g_c(Pn["C23"]), "C27": g_c(Pn["C27"]),
    "LEAK": Pn["LEAK"] * 1e6,
}
lines.append("/* Tone-forming network (tools/clav_net_ref.py): conductances in uS, Q12 (capacitors: 2C/T). */")
for k, v in G.items():
    lines.append(f"#define NG_{k} {q12(v)}")
lines.append(f"#define NET_N {net.N}")
for i, n in enumerate(net.NODES):
    lines.append(f"#define ND_{n} {i}")
cp = net.companion()
lines.append("/* Coupled windings La (IN-NB), Lb (NB-N1), Lc (gnd-N3): i = GM v + h, h' = GM v + AM i (GM uS Q20, AM Q30) */")
lines.append("static const int32_t NET_GM[3][3] = {" + ", ".join("{" + ", ".join(str(int(round(v * 1e6 * 2**20))) for v in row) + "}" for row in cp["Gm"]) + "};")
lines.append("static const int32_t NET_AM[3][3] = {" + ", ".join("{" + ", ".join(str(q30(v)) for v in row) + "}" for row in cp["Am"]) + "};")
lines.append(f"#define NET_G_L5 {int(round(cp['g_l5'] * 1e6 * 2**20))}   /* L5 + copper, uS Q20: i = g v + h, h' = g v + a i */")
lines.append(f"#define NET_A_L5 {q30(cp['a_l5'])}")
LEVER_MAX = net.LEVER_MAX
lines.append(f"#define LEVER_MAX {LEVER_MAX}u")
lines.append("/* The knee lever = R32 across IN: its conductance (uS Q12) per lever step. Step 0 = 10 ohm (silent), then a log")
lines.append(f" * taper {Pn['R32_MIN']:g} ohm .. {Pn['R32_MAX']:g} ohm (ESTIMATE: R32's 'special grading' is not printed). */")
lines.append(f"static const int32_t NET_G_R32[{LEVER_MAX + 1}] = {{")
gl = [q12(g_r(net.r32(i))) for i in range(LEVER_MAX + 1)]
for i in range(0, len(gl), 9):
    lines.append("    " + ", ".join(str(v) for v in gl[i:i + 9]) + ",")
lines.append("};")
# source and output scaling: source peak 1 mA at full scale (x = 32768 -> 1000 uA -> 65536000 units)
lines.append("#define NET_ISRC_MUL 2000   /* Q15 source sample -> current units (1 mA at full scale) */")
f = np.geomspace(50, 15000, 800)
zpk = np.abs(net.ac(0, LEVER_MAX, f)).max()       # ohm: the no-tablet response's peak, lever fully open
units = zpk * 1e-3 * 65536.0                       # V_OUT units for 1 mA at that frequency
mul = int(round(65536 * 14000 / units))
lines.append(f"#define NET_OUT_MUL {mul}   /* V_OUT units -> Q15, Q16: no tablets, lever open, 1 mA at the peak -> 14000 */")
lines.append("")

# ---- fine tuning (VR6 equivalent) ----------------------------------------------------------------------
lines.append("/* Fine tune: 2^(c/1200) in Q16 for c = -50..+50 cents. */")
tune = [int(round(65536 * 2 ** (c / 1200))) for c in range(-50, 51)]
lines.append("static const uint32_t TUNE_Q16[101] = {")
for i in range(0, 101, 10):
    lines.append("    " + ", ".join(str(v) for v in tune[i:i + 10]) + ",")
lines.append("};")
lines.append("")

OUT.write_text("\n".join(lines) + "\n")
print("wrote", OUT)
print("\n".join(r[3:] for r in report))
